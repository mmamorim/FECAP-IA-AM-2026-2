notas = [7.5, 8.0, 6.5, 9.0, 5.5, 7.0, 8.5]

# calcular a média "na mão"
soma = 0
for n in notas:
    soma += n
media = soma / len(notas)
print(media)

import numpy as np

notas_np = np.array(notas)

print(notas_np.mean())     # média, sem loop manual
print(notas_np.std())      # desvio padrão, de graça
print(notas_np.shape)      # forma do array: (7,) = 7 elementos, 1 dimensão
print(notas_np.dtype)      # tipo dos dados: float64

