import matplotlib.pyplot as plt

tamanhos = [10_000, 100_000, 1_000_000, 5_000_000, 10_000_000]
tempos_python = []
tempos_numpy = []

for n in tamanhos:
    lista = list(range(n))
    arr = np.arange(n)

    inicio = time.time()
    _ = [x * 2 for x in lista]
    tempos_python.append(time.time() - inicio)

    inicio = time.time()
    _ = arr * 2
    tempos_numpy.append(time.time() - inicio)

plt.plot(tamanhos, tempos_python, label="Python puro", marker="o")
plt.plot(tamanhos, tempos_numpy, label="NumPy", marker="o")
plt.xlabel("Quantidade de elementos")
plt.ylabel("Tempo (segundos)")
plt.title("Python puro vs NumPy")
plt.legend()
plt.show()

