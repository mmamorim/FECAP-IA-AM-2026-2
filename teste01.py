import numpy as np
import time

n = 10_000_000  # 10 milhões de elementos
lista_python = list(range(n))
array_numpy = np.arange(n)
print(lista_python[:20])
print(array_numpy[:20])

inicio = time.time()

resultado_python = [x * 2 for x in lista_python]

